def extra_talk_pairs() -> tuple[tuple[str, str], ...]:
    return _EXTRA_TALK


def stories_body() -> str:
    chunks = list(long_stories())
    turns = [format_pair(user, child) for user, child in _EXTRA_TALK]
    body = "\n".join(chunks) + "\n" + "".join(turns * 6)
    return body * 3
