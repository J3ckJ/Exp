def _story(person: str, first: str, second: str, time_line: str) -> str:
    return (
        f"{time_line} {person} дома. {person} {first}. "
        f"{person} {second}. Мы дома."
    )


def long_stories() -> tuple[str, ...]:
    out: list[str] = []
    for person in _PEOPLE:
        for first, second in _ACTIONS:
            for stamp in _MORNING:
                out.append(_story(person, first, second, stamp))
            for stamp in _EVENING:
                out.append(
                    f"{stamp} {person} дома. {person} {first}. "
                    f"{person} слушает. {person} отдыхает."
                )
    out.extend(
        (
            "Мама встаёт. Мама моет руки. Мама пьёт чай. Мама читает книгу. Папа открывает дверь.",
            "Папа идёт в сад. Папа видит кошку. Кошка пьёт молоко. Собака сидит дома. День светлый.",
            "Девочка рисует солнце. Мальчик читает книгу. Учитель видит окно. Учитель открывает окно.",
            "Я здесь. Я учусь говорить. Слова идут одно за другим. Сначала имя, потом действие.",
            "Друг говорит привет. Я говорю привет. Как дела? Хорошо. Спасибо.",
            "Ночь тёмная. Мама закрывает окно. Папа сидит дома. Спокойной ночи.",
            "Git помнит снимки файлов. Ветка указывает на снимок. Я ещё маленький. Я учусь.",
            "TLS делает рукопожатие. Потом речь шифруется. Если шаг не вышел, соединения нет.",
            "HTTP это вопрос и ответ. Клиент просит. Сервер отвечает.",
            "DNS это имена для адресов. Имя идёт по зонам. Есть главная копия.",
        )
    )
    return tuple(out)


